"""Ритм сбора per-site — единственный источник правды о расписании скрейпа.

Все пороги «данные устарели» в проекте выводятся отсюда, а не прописываются
по сайтам руками. Таймер сайта на проде вправе просыпаться чаще, чем здесь
записано (лишние ночи отсеет гвард в ``run``, см. `cadence_window_start`), но
не реже: реже — и данные устареют раньше, чем придёт следующий сбор.

Зачем отдельный модуль: расписание нужно и health-чекам (`src/health.py`), и
политике доверия каталогу (`src/product_policy.py`). Общий низкоуровневый
модуль без зависимостей избавляет от импорта одного в другой.

Рассинхрон карты с таймерами уже стоил ложной тревоги: 2026-10-04 aptekonline
перевели на недельный ритм, а пороги остались суточными — дашборд красил сайт
красным 6 дней из 7, хотя он собирался ровно по графику. **Меняешь таймер —
меняй и эту карту.** И в обратную сторону: суточная карта при недельном
будильнике делает сайт «просроченным» шесть дней из семи — поэтому, возвращая
сайт на сутки, сначала ставят суточный будильник на сервере (при недельной
карте лишние ночи `run` пропускает сам), и только потом выкладывают карту.
"""

from __future__ import annotations

import math
from datetime import datetime, timedelta

SITE_SCRAPE_CADENCE_HOURS: dict[str, int] = {
    # Все три сайта — полный сбор каждую ночь, решение владельца 2026-10-13:
    # клиент попросил присылать разницу цен ежедневно, а сравнивать вчерашнюю
    # цену с недельной давности — значит присылать разницу, которой уже нет.
    # С 2026-10-06 (aptekonline — с 2026-10-04) все три собирались раз в неделю.
    # Платный из трёх один aptekonline: его Cloudflare пропускает только жилые
    # адреса. Через Decodo полный сбор — около 51 МиБ (оценка по июньским
    # прогонам, счётчиком не замерено), при $4 за ГБ это примерно $6 в месяц
    # вместо $0,9; неделя появилась, когда тот же сбор шёл через ScraperAPI и
    # стоил $149 в месяц против $49.
    "pharmonline": 24,
    "aptekonline": 24,
    "aloe": 24,
}
_DEFAULT_CADENCE_HOURS = 24

# Запас поверх ритма на jitter/retry и длительность самого прогона: данные
# считаются устаревшими только когда пропущен ЦЕЛЫЙ запуск плюс этот запас.
CADENCE_GRACE_HOURS = 6


def site_cadence_hours(site: str) -> int:
    """Ожидаемый интервал между полными сборами сайта (часы)."""
    return SITE_SCRAPE_CADENCE_HOURS.get(site, _DEFAULT_CADENCE_HOURS)


def site_max_age_hours(site: str) -> int:
    """Возраст, после которого данные сайта «просрочены»: ритм + запас.

    Суточный сайт → 30ч, недельный → 174ч.
    """
    return site_cadence_hours(site) + CADENCE_GRACE_HOURS


def site_cadence_days(site: str) -> int:
    """Ритм сбора в днях, вверх: суточный → 1, недельный → 7."""
    return max(1, math.ceil(site_cadence_hours(site) / 24))


# Начало отсчёта окон ритма: воскресенье 22:00 UTC. Суточное окно открывается
# каждый вечер в 22:00 UTC, недельное — в ночь на понедельник.
#
# Граница подобрана под будильники полного сбора: они стоят на ночь по времени
# прод-хоста, 01:00 и повтор в 03:15 Europe/Berlin, то есть от 23:00 UTC (01:00
# летом) до 02:15 UTC (03:15 зимой). Требований два, и оба проверяет
# tests/test_cadence_guard.py:
#   * граница не позже чем за час до самого раннего будильника — иначе ночной
#     запуск попал бы в прошлое окно;
#   * от границы до самого позднего будильника вместе с его случайной задержкой
#     — не больше CADENCE_GRACE_HOURS минус час. Сбор, сделанный вручную сразу
#     после границы, закрывает окно, и следующий плановый придёт позже обычного
#     ровно на этот зазор; он обязан уложиться в порог «данные устарели».
# Часы будильников тест читает из infra/systemd. Переносишь их или хост в
# другой часовой пояс — пересчитай границу.
CADENCE_ANCHOR_UTC = datetime(2024, 1, 7, 22, 0)


def cadence_window_start(site: str, now: datetime) -> datetime:
    """Начало текущего окна ритма сайта (naive UTC, как в столбцах БД).

    Полный сбор положен раз в окно: суточному сайту — раз в сутки, недельному —
    раз в календарную неделю. Плановый запуск собирает, если в текущем окне
    успешного сбора ещё не было; будильников за ночь два, и второй достаётся
    только сайту, чей первый сбор не удался.

    Почему окно, а не «прошло N часов с прошлого сбора». Возраст сравнивается с
    ритмом в ту же минуту суток, в которую сбор шёл в прошлый раз, и исход
    решают минуты: длительность прогона и случайная задержка таймера уводили
    недельный сбор на восьмой день, а суточный уводили бы на вторую ночь. И
    хуже того — после любого сбора не по графику (ручной сбор днём) таймер
    пропустил бы свою ночь целиком. Окно не зависит ни от того, как часто
    просыпается таймер, ни от того, когда был прошлый сбор.
    """
    step = timedelta(hours=site_cadence_hours(site))
    return CADENCE_ANCHOR_UTC + ((now - CADENCE_ANCHOR_UTC) // step) * step
