"""Ритм сбора per-site — единственный источник правды о расписании скрейпа.

Все пороги «данные устарели» в проекте выводятся отсюда, а не прописываются
по сайтам руками. Таймер сайта на проде вправе просыпаться чаще, чем здесь
записано (лишние ночи отсеет гвард в ``run``, см. `cadence_window_start`), но
не реже: реже — и данные устареют раньше, чем придёт следующий сбор.

Зачем отдельный модуль: расписание нужно и health-чекам (`src/health.py`), и
политике доверия каталогу (`src/product_policy.py`). Общий низкоуровневый
модуль без зависимостей избавляет от импорта одного в другой.

Рассинхрон карты с таймерами уже стоил ложной тревоги: 2026-10-04 aptekonline
перевели на недельный ритм (его Cloudflare обходится только платным выходом,
ежедневный сбор ≈$149/мес против $49 за недельный), а пороги остались
суточными — дашборд красил сайт красным 6 дней из 7, хотя он собирался ровно
по графику. **Меняешь таймер — меняй и эту карту.**
"""

from __future__ import annotations

import math
from datetime import datetime, timedelta

SITE_SCRAPE_CADENCE_HOURS: dict[str, int] = {
    # Все три сайта — недельный полный сбор, решение владельца 2026-10-06.
    # aptekonline ушёл на неделю раньше, 2026-10-04 (цена обхода Cloudflare).
    # Частичные тики (intraday, watchlist) живут отдельно и остаются суточными —
    # они обновляют приоритетные товары и кормят мгновенные ценовые алерты.
    "pharmonline": 168,
    "aptekonline": 168,
    "aloe": 168,
}
_DEFAULT_CADENCE_HOURS = 24

# Запас поверх ритма на jitter/retry и длительность самого прогона: данные
# считаются устаревшими только когда пропущен ЦЕЛЫЙ запуск плюс этот запас.
CADENCE_GRACE_HOURS = 6


def site_cadence_hours(site: str) -> int:
    """Ожидаемый интервал между полными сборами сайта (часы)."""
    return SITE_SCRAPE_CADENCE_HOURS.get(site, _DEFAULT_CADENCE_HOURS)


def site_max_age_hours(site: str) -> int:
    """Возраст, после которого данные сайта «просрочены»: ритм + запас.

    Суточный сайт → 30ч, недельный → 174ч.
    """
    return site_cadence_hours(site) + CADENCE_GRACE_HOURS


def site_cadence_days(site: str) -> int:
    """Ритм сбора в днях, вверх: суточный → 1, недельный → 7."""
    return max(1, math.ceil(site_cadence_hours(site) / 24))


# Начало отсчёта окон ритма: воскресенье 22:00 UTC. Недельное окно открывается
# в ночь на понедельник.
#
# Граница подобрана под таймеры полного сбора: они стоят на ночь понедельника
# по времени прод-хоста, 01:00–03:00 Europe/Berlin, то есть от вс 23:00 UTC
# (01:00 летом) до пн 02:00 UTC (03:00 зимой). Требований два, и оба проверяет
# tests/test_cadence_guard.py:
#   * граница раньше самого раннего таймера, с запасом на его случайную
#     задержку, — иначе понедельничный запуск попал бы в прошлую неделю;
#   * от границы до самого позднего таймера не больше CADENCE_GRACE_HOURS минус
#     час. Сбор, сделанный вручную сразу после границы, закрывает неделю, и
#     следующий плановый придёт позже обычного ровно на этот зазор; он обязан
#     уложиться в порог «данные устарели».
# Переносишь таймеры или хост в другой часовой пояс — пересчитай границу.
CADENCE_ANCHOR_UTC = datetime(2024, 1, 7, 22, 0)


def cadence_window_start(site: str, now: datetime) -> datetime:
    """Начало текущего окна ритма сайта (naive UTC, как в столбцах БД).

    Полный сбор положен раз в окно: недельному сайту — раз в календарную
    неделю, суточному — раз в сутки. Плановый запуск собирает, если в текущем
    окне успешного сбора ещё не было.

    Почему окно, а не «прошло N часов с прошлого сбора». Возраст сравнивается с
    ритмом в ту же минуту суток, в которую сбор шёл неделю назад, и исход
    решают минуты: длительность прогона и случайная задержка таймера уводили
    недельный сбор на восьмой день. И хуже того — после любого сбора не по
    графику (повтор упавшего в среду) недельный таймер пропустил бы свой
    понедельник целиком и вернулся через неделю. Окно не зависит ни от того,
    как часто просыпается таймер, ни от того, когда был прошлый сбор.
    """
    step = timedelta(hours=site_cadence_hours(site))
    return CADENCE_ANCHOR_UTC + ((now - CADENCE_ANCHOR_UTC) // step) * step
